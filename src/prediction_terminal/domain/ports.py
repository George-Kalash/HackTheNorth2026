from datetime import datetime
from typing import Any, Protocol

from .books import BookSnapshot
from .history import PriceHistory, PriceType
from .markets import Event, VenueMarket


class Clock(Protocol):
    def now(self) -> datetime: ...


class MarketFeed(Protocol):
    async def search(self, query: str) -> list[Event]: ...
    async def event(self, external_id: str) -> Event: ...
    async def book(self, market: VenueMarket) -> BookSnapshot: ...
    async def history(self, market: VenueMarket, price_type: PriceType, days: int) -> PriceHistory: ...


class Repository(Protocol):
    def get(self, table: str, id: str) -> dict[str, Any] | None: ...
    def list(self, table: str, limit: int = 100, offset: int = 0) -> list[dict[str, Any]]: ...
    def put(self, table: str, id: str, payload: dict[str, Any], **keys: Any) -> None: ...
    def delete(self, table: str, id: str) -> None: ...
